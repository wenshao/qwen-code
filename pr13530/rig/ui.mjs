// Real WebShell (vite, ManagedAgentWebShell) against the PR's Spring: approval card of a definition Session.
import { chromium } from '/Users/wenshao/git/pr13530-head/node_modules/playwright/index.mjs';
import { client, sql, sleep, modelLog, result } from './lib.mjs';
const db = 'h1';
const c = client(db);
const run = Date.now().toString(36).slice(-5);
const f2 = { type: 'hosted_profile', profile: 'hosted-workspace-files/2' };
const a = await c.createAgent({ model: { id: 'model-a' }, instructions: `INSTR-UI-R1-${run.toUpperCase()}`, tools: [f2], permission_policy: { approval_mode: 'default' }, metadata: { name: 'pr13530 ui rig' } });
const id1 = `ui1${run}`;
const s1 = await c.createSession({ agentId: a.json.id, prompt: `D8::write::${id1} please write the note file` });
const w1 = await c.waitTurn(s1.json.id, { stopOnAction: true, timeout: 120 });
console.log('s1', s1.json.id, s1.json.agent_revision, w1);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(`http://localhost:5530/e2e/fixtures/rig-13530.html?actor=rig-actor&tenant=rig&session=${s1.json.id}&lang=en`);
const allow = page.locator('[data-web-shell-permission-option][data-option-id="allow"]').first();
await allow.waitFor({ timeout: 45000 });
await sleep(1500);
await page.screenshot({ path: 'fig/raw/ui-01-approval-rev1.png' });
result('ui', 'definition Session (rev 1, default) shows a write approval card in WebShell', true, `session=${s1.json.id} turn=${w1}`);
await allow.click({ timeout: 15000 }).catch(async (e) => { console.log('click failed, using keyboard shortcut 2:', String(e).slice(0, 120)); await allow.focus(); await page.keyboard.press('2'); });
const done = await c.waitTurn(s1.json.id, { timeout: 120 });
await sleep(2500);
await page.screenshot({ path: 'fig/raw/ui-02-after-allow.png' });
const file = sql(db, `SELECT 1`) && (await import('node:fs')).existsSync(`${c.st.mount}/w-${id1}.txt`);
result('ui', 'Allow in the real card resumes the Turn and writes the file', / COMPLETED /.test(done + ' ') && file, `${done} file=${file}`);
// Revision 2 with yolo: a new Session writes without a card.
const u = await c.updateAgent(a.json.id, { model: { id: 'model-b' }, instructions: `INSTR-UI-R2-${run.toUpperCase()}`, tools: [f2], permission_policy: { approval_mode: 'yolo' } });
const id2 = `ui2${run}`;
const s2 = await c.createSession({ agentId: a.json.id, prompt: `D8::write::${id2} please write the note file` });
const w2 = await c.waitTurn(s2.json.id, { stopOnAction: true, timeout: 120 });
await page.goto(`http://localhost:5530/e2e/fixtures/rig-13530.html?actor=rig-actor&tenant=rig&session=${s2.json.id}&lang=en`);
await sleep(6000);
await page.screenshot({ path: 'fig/raw/ui-03-rev2-yolo.png' });
const cards = await page.locator('[data-web-shell-permission-option]').count();
result('ui', 'revision-2 yolo Session: no card, file written', / COMPLETED /.test(w2 + ' ') && cards === 0 && (await import('node:fs')).existsSync(`${c.st.mount}/w-${id2}.txt`), `${w2} rev=${s2.json.agent_revision} cards=${cards}`);
console.log(JSON.stringify({ errors: errors.slice(0, 3), s1: s1.json.id, s2: s2.json.id, agent: a.json.id, rev2: u.json.revision, m1: modelLog((x) => x.id === id1).map((x) => x.model), m2: modelLog((x) => x.id === id2).map((x) => x.model) }));
await browser.close();
