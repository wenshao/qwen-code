// VERIFICATION RIG ONLY: the Hosted Harness dies while an approval is pending (design section 4/8: stranded until Stage G).
// Needs `default` mode with a 30 s approval timeout. usage: DB=<db> node s7c-harness-restart.mjs <workspace> <storage>
import { execSync } from 'node:child_process';
import { api, one, sql, ensureWorkspace, createSession, listActions, getAction, respond, getOp, waitPending, waitTurn, opRow, actionRow, sessionRow, readWs, executions, setTapRules, tapEntries, Report, sleep, j, RIG, DB } from './lib.mjs';
const [workspace = 'ws-b', storage = 'b'] = process.argv.slice(2);
const R = new Report('s7c-harness-restart');
const idOf = (a) => a.actionId ?? a.id;
const opId = (o) => o.operationId ?? o.id;
const sh = (c) => execSync(c, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
ensureWorkspace(workspace, `st-${storage}`);
setTapRules([]);
const f = `hk-${Date.now().toString(36)}.txt`;
const c = await createSession('public', workspace, `D6_WRITE name=${f} content=after-harness-restart`);
const S = c.session;
const p = await waitPending(S);
const A = idOf(p.action);
const expires = p.action.expires_at;
R.check('pending approval with a 30 s timeout', !p.timeout && expires - p.action.created_at === 30000, `action=${A}`);
R.say(sh(`${RIG}/stop.sh ${DB} harness KILL`));
R.say(sh(`${RIG}/harness.sh ${DB} ${process.env.DIST ?? "head"}`).split('\n').slice(-1)[0]);
R.say(sh(`${RIG}/stop.sh ${DB} spring TERM`));
R.say(sh(`${RIG}/spring.sh ${process.env.JAR ?? "head"} ${DB} default 30s`).split('\n').slice(-1)[0]);
const left = expires - Date.now();
R.note('both processes restarted', `${left} ms before the approval's expiry`);
const l = await listActions('public', S);
R.check('the approval is still listed as requested', l.json.data?.length === 1 && l.json.data[0].id === A, j(l.json.data?.map((a) => [a.id, a.state])));
const r = await respond('public', S, p.action, 'allow', { key: 'hk-1' });
R.check('an answer before the expiry is admitted (202)', left > 0 && r.status === 202, `HTTP ${r.status} ${j(r.json)}`);
const OP = opId(r.json);
await sleep(Math.max(0, expires - Date.now()) + 6000);
const o1 = (await getOp('public', S, OP)).json;
const calls = tapEntries().filter((e) => e.t > new Date(p.action.created_at).toISOString() && e.path.includes(S) && e.method === 'POST');
R.note('Java -> Harness calls for this Session after the restart', j(calls.map((e) => `${e.path.split(S)[1]} ${e.status ?? e.error}`).reduce((m, k) => ((m[k] = (m[k] ?? 0) + 1), m), {})));
R.check('6 s after the expiry: the Action is still requested, the operation still running', actionRow(A)[0] === 'requested' && o1.status === 'running', `action=${actionRow(A)[0]} op=${o1.status}/${o1.delivery_state} attempts=${opRow(OP)[3]}`);
const l2 = await listActions('public', S);
R.check('the pending list still returns it after its expiry time (no local expiry)', l2.json.data?.length === 1 && l2.json.data[0].expires_at < Date.now(), `listed=${l2.json.data?.length} expired ${Date.now() - expires} ms ago`);
const late = await respond('public', S, p.action, 'allow', { key: 'hk-2' });
R.check('a new answer after the expiry -> 409 action_expired', late.status === 409 && late.json.error?.code === 'action_expired', `HTTP ${late.status} ${j(late.json.error)}`);
R.check('fail closed: the write never ran', readWs(storage, `child/${f}`) === null && executions(S) === 0, `file=${readWs(storage, `child/${f}`)} executions=${executions(S)}`);
const pub = await api('GET', `/v1/agents/sessions/${S}`);
R.note('Session and Turn as the client sees them', `session=${pub.json.status} turn=${pub.json.active_turn?.status} db turn=${j(sql(`SELECT status, COALESCE(error_code,''), retry_count FROM managed_agent_turn WHERE session_id='${S}'`)[0])}`);
R.done({ session: S, operation: OP });
