// S17b: the same FIFO marker against the c21efbdfa1 server (before the regular-file check), driver-side Session.
import fs from 'node:fs';
import * as L from './lib.mjs';
L.openLog('s17b-fifo-c21efbdf');
const { say, sleep } = L; const R = '/srv/w1a'; const MARK = '.qwen-managed-storage.json';
say(L.hostFacts()); say(L.svc('status').replace(/\n/g, ' '));
L.seedWs('ws-c', 'c');
L.svc('stop');
L.sayMaint('s17b-register-c', L.maint(['register', L.TENANT, 'st-c', `${R}/c`, '6a0e1c7e-9f0a-4c6b-9d5e-2c4f1b8a7d31', '--offline-confirmed']));
say('  ', L.svc('start').split(' ===')[0]);
const rig = await L.startRig('s17b');
const S = new L.HSession(rig.h, await L.createSession('ws-c'), 'ws-c'); await S.create(L.FILES);
let r = await S.prompt('WRITE before.txt x'); say(`control Turn with a regular marker: ${r.terminal?.map((t) => t.type).join(',')}`);
fs.renameSync(`${R}/c/${MARK}`, `${R}/c/${MARK}.real`); L.sh(`mkfifo ${R}/c/${MARK}`);
say(`marker replaced by a FIFO (${L.sh(`stat -c '%F' ${R}/c/${MARK}`)})`);
const mark = rig.proxy.ledger.length; const t0 = Date.now();
const sub = await S.submit('WRITE fifo.txt x'); say(`next Turn admitted: ${sub.status}`);
await sleep(40000);
const st = await S.status();
say(`after 40 s: active prompt=${st?.hasActivePrompt}; broker requests: ${rig.proxy.ledger.slice(mark).map((e) => `${L.opName(e.url)}→${e.status ?? 'NO REPLY YET'}`).join('  ')}; fifo.txt ${fs.existsSync(`${R}/c/project/fifo.txt`) ? 'WRITTEN' : 'not written'}`);
const h = await L.api('GET', '/actuator/health', undefined, { timeoutMs: 5000 }); say(`server health: ${h.status}`);
const jst = L.sh("pid=$(systemctl show -p MainPID --value qwen-w1a.service); timeout 10 /opt/qwen/jdk/bin/jstack $pid 2>/dev/null | grep -B2 -A12 'FileChannelImpl\\|UnixNativeDispatcher.open\\|FileDispatcherImpl' | grep -E '^\"|at (sun.nio|java.nio|com.alibaba)' | head -12 || true");
say(`threads blocked opening the marker:\n${jst || '<none found>'}`);
const L2 = L.sh(`cd /tmp && timeout 25 /opt/qwen/node -e "fs=require('fs');const t=Date.now();const w=fs.openSync('${R}/c/${MARK}','w');fs.closeSync(w);console.log('writer opened after',Date.now()-t,'ms')" || echo 'no reader'`);
say(`a writer opens the FIFO once (unblocks one reader): ${L2}`);
await sleep(3000);
say(`then: broker requests: ${rig.proxy.ledger.slice(mark).map((e) => `${L.opName(e.url)}→${e.status ?? 'NO REPLY YET'}${e.code ? `(${e.code})` : ''}`).join('  ')}; elapsed ${Math.round((Date.now() - t0) / 1000)} s`);
fs.rmSync(`${R}/c/${MARK}`); fs.renameSync(`${R}/c/${MARK}.real`, `${R}/c/${MARK}`);
await rig.stop().catch(() => {});
say('S17B-DONE');
