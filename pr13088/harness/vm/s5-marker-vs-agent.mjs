// S5: the root marker lives inside the tree the agent's own tools work on.
// Storage c is a git repository at the storage root and the Session cwd is "." (the repository root).
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import * as L from './lib.mjs';
L.openLog('s5-marker-vs-agent');
const { say } = L; const R = '/srv/w1a'; const MARK = '.qwen-managed-storage.json';
say(L.hostFacts()); say(L.svc('status').replace(/\n/g, ' '));
L.seedWs('ws-c', 'c'); L.seedWs('ws-c2', 'c');
L.sh(`cd ${R}/c && git init -q -b main . && git config user.email rig@example.invalid && git config user.name rig && echo 'build/' > .gitignore && echo hello > README.md && git add -A && git commit -q -m init && git log --oneline | head -1`);
L.svc('stop');
const op = randomUUID();
L.sayMaint('register-c', L.maint(['register', L.TENANT, 'st-c', `${R}/c`, op, '--offline-confirmed']));
say('  ', L.svc('start').split(' ===')[0]);
const rig = await L.startRig('s5');
let mark = 0; const since = () => { const s = L.ledgerStr(rig.proxy.ledger, mark); mark = rig.proxy.ledger.length; return s; };
const out = (r) => { for (const t of L.toolTrace(r.events)) if (t.startsWith('result')) return t.replace(/\\n/g, ' ⏎ ').slice(0, 420); return '<no tool result>'; };
const term = (r) => r.terminal?.map((t) => t.type).join(',') || '<no terminal event>';

let sid;
try { sid = await L.createSession('ws-c', '.'); } catch (e) { say('create with cwd ".":', String(e.message)); }
const S = new L.HSession(rig.h, sid, 'ws-c');
say(`Shell Session S on ws-c with cwd_relative "." : create=${(await S.create(L.SHELL)).status}`);
let r = await S.prompt(L.shell64('pwd; git status --porcelain'));
say('1. `git status --porcelain` ->', term(r)); say('     ', out(r));
r = await S.prompt(L.shell64(`cat ${MARK}`));
say(`2. \`cat ${MARK}\` ->`, term(r)); say('     ', out(r));
const lastTool = rig.model.state.log.at(-1);
say(`      (the tool result above was sent to the model provider: request with ${lastTool.messages} messages, ${lastTool.toolResults} tool results)`);
say(`   inspect: ${L.inspect('c').out}`);
r = await S.prompt(L.shell64('mkdir -p build && echo artifact > build/out.o && echo scratch > notes.tmp && git stash -u && git status --porcelain && ls -a'));
say('3. `git stash -u` (stash untracked work before switching branches) ->', term(r)); say('     ', out(r)); say('      broker:', since());
say(`   marker on disk: ${fs.existsSync(`${R}/c/${MARK}`) ? 'present' : 'ABSENT'}; inspect: ${L.inspect('c').out}`);
say(`   S status: ${JSON.stringify(await S.status())}; row: ${L.mstr(L.mountRow('c'))}`);
r = await S.prompt(L.shell64('git stash pop && git status --porcelain'));
say('4. the agent tries to undo it with `git stash pop` ->', term(r), JSON.stringify(r.terminal?.[0]?.data ?? {}).slice(0, 160)); say('      broker:', since());
const N = new L.HSession(rig.h, await L.createSession('ws-c2', '.'), 'ws-c2');
say(`5. another Workspace on the same storage (ws-c2), new file Session: create=${(await N.create(L.FILES)).status}`);
r = await N.prompt('WRITE other.txt x'); say('   tool Turn ->', term(r)); say('      broker:', since());
say('6. what the operator can do with the maintenance entry (service stopped):');
await S.detach(); await N.detach(); L.svc('stop');
L.sayMaint('s5-register-same-op', L.maint(['register', L.TENANT, 'st-c', `${R}/c`, op, '--offline-confirmed']));
L.sayMaint('s5-register-new-op', L.maint(['register', L.TENANT, 'st-c', `${R}/c`, randomUUID(), '--offline-confirmed']));
L.sayMaint('s5-fence', L.maint(['fence', L.TENANT, 'st-c', `${R}/c`, '1', randomUUID(), '--offline-confirmed']));
L.sayMaint('s5-restore-original', L.maint(['restore-original', L.TENANT, 'st-c', `${R}/c`, '1', op, '--offline-confirmed']));
say(`   marker: ${fs.existsSync(`${R}/c/${MARK}`) ? 'present' : 'ABSENT'}; inspect: ${L.inspect('c').out}`);
say('7. manual repair outside the product: `git stash pop` run by the operator on the host brings the marker back');
say('   ', L.sh(`cd ${R}/c && git stash pop -q && git status --porcelain | tr '\\n' ' '`));
say(`   inspect: ${L.inspect('c').out}`);
say('  ', L.svc('start').split(' ===')[0]);
say(`   S load=${(await S.load()).status}`); mark = rig.proxy.ledger.length;
r = await S.prompt(L.shell64('echo back > back.txt; ls -a | tr "\\n" " "')); say('   S next Shell Turn ->', term(r)); say('     ', out(r)); say('      broker:', since());

say('== variant: `git clean -fdx`');
r = await S.prompt(L.shell64('git clean -fdx 2>&1 | tr "\\n" " "')); say('8. `git clean -fdx` ->', term(r)); say('     ', out(r));
say(`   marker on disk: ${fs.existsSync(`${R}/c/${MARK}`) ? 'present' : 'ABSENT (deleted, not recoverable from git)'}; inspect: ${L.inspect('c').out}`);
mark = rig.proxy.ledger.length;
r = await S.prompt(L.shell64('echo after-clean')); say('   next Shell Turn ->', term(r)); say('      broker:', since());
say('9. manual repair: the operator rewrites the marker from the SQL row (the same eight fields)');
await S.detach(); L.svc('stop');
const m = L.mountRow('c');
const body = JSON.stringify({ version: 1, tenantId: m.tenant, storageId: m.storage, root: m.root, hostId: m.hostId, device: m.device, inode: m.inode, registrationId: m.registrationId });
fs.writeFileSync(`${R}/c/${MARK}`, body);
say(`   wrote ${body.length} bytes; inspect: ${L.inspect('c').out}`);
say('  ', L.svc('start').split(' ===')[0]); say(`   S load=${(await S.load()).status}`); mark = rig.proxy.ledger.length;
r = await S.prompt(L.shell64('echo repaired')); say('   next Shell Turn ->', term(r)); say('      broker:', since());

say('== variant: file profile, cwd ".", write_file on the marker path');
const F = new L.HSession(rig.h, await L.createSession('ws-c2', '.'), 'ws-c2');
say(`file Session F create=${(await F.create(L.FILES)).status}`);
r = await F.prompt(`WRITE ${MARK} {}`); say(`10. write_file ${MARK} ->`, term(r)); say('     ', out(r)); say('      broker:', since());
say(`   marker now: ${JSON.stringify(fs.readFileSync(`${R}/c/${MARK}`, 'utf8')).slice(0, 80)}; inspect: ${L.inspect('c').out}`);
r = await F.prompt('WRITE after.txt x'); say('   next file Turn ->', term(r)); say('      broker:', since());
await rig.stop(); say('S5-DONE');
