// PR #12868: what can still be observed after a provider Session is released.
import { randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { ROOTS, BROKER_URL, BROKER_TOKEN, ARM, attempt, brief, broker, createSession, executions, ledger, ledgerMark, loadProvider, openLog, prepareRequest, say, wire } from './lib.mjs';

openLog(`s10-after-release-${ARM}`);
const { BrokerManagedRuntimeProvider } = await loadProvider();
const provider = new BrokerManagedRuntimeProvider({ baseUrl: BROKER_URL, token: BROKER_TOKEN });
const harness = await createSession();
const cwd = fs.realpathSync(path.join(ROOTS, 'plain'));
const runtimeSessionId = randomUUID();
const request = prepareRequest(runtimeSessionId, 'bootstrap', cwd);
const client = await provider.getToolV2Client(request, { harnessSessionId: harness });
await client.fileHistory.bind({ ownerSessionId: harness, ownerRuntimeSessionId: runtimeSessionId, executionCwd: cwd, snapshots: [] });
const manifest = await client.manifest();
const identity = { sessionId: runtimeSessionId, promptId: 'p1', callId: 'c1', capabilityDigest: manifest.capabilityDigest, policyRevision: manifest.policyRevision };
await client.beginTurn({ ...identity, callId: 'turn' });
const prepared = await client.prepare(identity, 'write_file', { file_path: path.join(cwd, `after-${runtimeSessionId.slice(0, 6)}.txt`), content: 'x\n' });
const reference = Object.fromEntries(['sessionId', 'promptId', 'callId', 'capabilityDigest', 'policyRevision', 'invocationId', 'argsDigest'].map((k) => [k, prepared[k]]));
const reserved = await client.prepareExecution(reference);
await client.confirm(reference, 'proceed_once');
await client.preflight(reference);
await client.startExecution(reference, reserved.executionCallId);
say('before', `history via provider: ${brief(await attempt(() => client.fileHistory.snapshot())).slice(0, 60)}`);
say('release', brief(await attempt(() => provider.release(runtimeSessionId, request, { terminal: true }))));
const mark = ledgerMark();
const base = { protocolVersion: 1, requestId: randomUUID(), harnessSessionId: harness };
const control = (operation) => broker('POST', `tool-sessions/${runtimeSessionId}/control`, { ...base, operation });
const history = await control({ kind: 'history' });
const status = await broker('GET', `executions/${reserved.executionCallId}?requestId=${randomUUID()}&harnessSessionId=${harness}&runtimeSessionId=${runtimeSessionId}`);
const cancel = await broker('POST', `executions/${reserved.executionCallId}:cancel`, { ...base, runtimeSessionId });
say('after', `Broker control[history]: ${history.status} ${history.code}`);
say('after', `Broker GET execution: ${status.status} ${status.code}`);
say('after', `Broker cancel: ${cancel.status} ${cancel.code}`);
say('after', `provider history: ${brief(await attempt(() => client.fileHistory.snapshot())).slice(0, 130)}`);
say('after', `provider status: ${brief(await attempt(() => client.status(reference))).slice(0, 130)}`);
say('after', `Broker -> worker requests caused by these five observations: ${ledger(mark).length} ${wire(ledger(mark)).join(', ')}`);
say('after', `durable row: ${JSON.stringify(executions(runtimeSessionId).map((r) => `${r.state}/${r.status}`))}`);
provider.dispose();
