// VERIFICATION RIG ONLY (PR #13163): real model writes step files one per call; after step-02 the creator's
// can_create is revoked and the creator clicks Cancel in the real Managed panel. Does the Turn stop?
// usage: DB=<db> node c15-real-ui-cancel.mjs <workspace> <storage> <lang>
import fs from 'node:fs';
import { launch, open, shot, calls, sleep } from './ui.mjs';
import { api, sql, one, register, waitTurn, turnRow, executions, wsFile, Report, TENANT, j } from './lib.mjs';
const [WS, ST, LANG] = [process.argv[2], process.argv[3], process.argv[4] ?? 'en'];
const r = new Report(`c15-real-ui-${LANG}-${WS}`);
if (one(`SELECT COUNT(*) FROM managed_workspace_registry WHERE tenant_id='${TENANT}' AND workspace_id='${WS}'`) === '0') register(WS, `st-${ST}`);
const W = `tenant_id='${TENANT}' AND workspace_id='${WS}'`;
sql(`UPDATE managed_workspace_access SET can_read=TRUE, can_create=TRUE WHERE ${W} AND actor_id='alice'`);
const k = (s) => `${s}-${WS}-${Date.now()}`;
const dir = wsFile(ST, 'child');
const steps = () => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^step-\d+\.txt$/.test(f)).sort() : []);
const c = await api('POST', '/v1/agents/sessions', { agent_id: 'qwen-code', input: [{ type: 'input_text', text: 'Create a file named notes.txt in the current directory containing exactly one line: alpha-7319. Use the write_file tool. Reply with one short sentence.' }], workspace: { workspace_id: WS, cwd_relative: 'child' } }, { actor: 'alice', key: k('create') });
const S = c.json.id;
r.check('Turn 1 (real model) COMPLETED', (await waitTurn(S, { timeoutMs: 240_000 })).status === 'COMPLETED');
const sub = await api('POST', `/v1/agents/sessions/${S}/events`, { type: 'agent.session.input.message', input: [{ type: 'input_text', text: 'Create twelve files in the current directory, strictly one at a time: step-01.txt, step-02.txt, ..., step-12.txt. Each file contains only its own two-digit number. Make exactly one write_file tool call per assistant message and wait for its result before creating the next file. Never put two tool calls in one message. When all twelve exist, reply DONE.' }] }, { actor: 'alice', key: k('steps') });
const browser = await launch();
const v = await open(browser, { arm: 'head', actor: 'alice', lang: LANG, session: S });
await v.page.locator('[data-managed-workspace-binding]').waitFor({ state: 'visible', timeout: 30_000 }).catch(() => {});
const start = Date.now();
while (steps().length < 2 && Date.now() - start < 180_000) await sleep(100);
sql(`UPDATE managed_workspace_access SET can_create=FALSE WHERE ${W} AND actor_id='alice'`);
const atRevoke = steps().length;
await v.page.reload({ waitUntil: 'load' });
await v.page.locator('[data-managed-workspace-binding]').waitFor({ state: 'visible', timeout: 30_000 }).catch(() => {});
const btn = v.page.getByRole('button', { name: /^(Cancel turn|取消本轮)$/ });
await btn.first().waitFor({ state: 'visible', timeout: 15_000 }).catch(() => {});
const shown = await btn.count();
const atClick = steps().length;
await shot(v.page, `c15-real-1-revoked-${LANG}`);
const t0 = Date.now();
if (shown) await btn.first().click();
await sleep(1000);
const cc = calls(v.net, '/turns/cancel').at(-1);
const end = await waitTurn(S, { timeoutMs: 120_000 });
await sleep(3000);
await shot(v.page, `c15-real-2-after-${LANG}`);
await v.context.close();
await browser.close();
sql(`UPDATE managed_workspace_access SET can_create=TRUE WHERE ${W} AND actor_id='alice'`);
await sleep(15_000);
r.note('step files at revoke / at click / 15 s after the end', `${atRevoke} / ${atClick} / ${steps().length}`);
r.note('Cancel button shown after the revoke', `${shown}`);
r.note('panel cancel request', `${cc?.status}`);
r.note('Turn end', `${end.status} ${end.error} ${end.timeout ? '(not terminal)' : `at +${Date.now() - t0 - 3000 - 15_000} ms`}`);
r.note('Turn history', j(turnRow(S)));
r.done({ session: S, atRevoke, atClick, final: steps().length, shown, cancel: cc?.status ?? null, end });
process.exit(0);
